import assert from "node:assert/strict";

// Runs inside browser-qa's isolated component server, never against hosted data.
export async function runCharacterOrganizationQA({ evaluate, cdp, click, input, waitFor, navigate, screenshot, fixtureOrigin }) {
  await cdp("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1080, deviceScaleFactor: 1, mobile: false });
  await navigate(fixtureOrigin);
  await waitFor("document.querySelector('.world-map')");
  await evaluate("localStorage.setItem('atlas-map-tour-v1', 'done')");
  await click('#test-characters');
  await waitFor("document.querySelector('.character-form button[type=submit]:not(:disabled)')");
  await input('[name="character-name"]', 'Bilingual tester');
  await input('[name="character-title"]', 'Independent explorer');
  await click('.character-form button[type=submit]');
  assert.equal(await evaluate("document.querySelector('[name=character-name-fa]').validity.valueMissing"), true, 'Persian name is required');
  await input('[name="character-name-fa"]', 'شخصیت دوزبانه');
  await input('[name="character-title-fa"]', 'کاوشگر مستقل');
  await click('.character-form button[type=submit]');
  await waitFor("[...document.querySelectorAll('.custom-character h3')].some(el => el.textContent === 'Bilingual tester')");
  const read = () => evaluate("JSON.parse(localStorage.getItem('atlas-people-v1:fixture-a'))");
  const draft = (await read()).people.find(person => person.name === 'Bilingual tester');
  assert.ok(draft);
  await click('#test-directory');
  await waitFor("document.querySelector('.directory')");
  await input('#directory-group-name', 'Favorites');
  await click('.group-form button[type=submit]');
  await waitFor("document.querySelector('[aria-label=\"Filter by group\"]').options.length === 2");
  const card = `.person-card[data-person-id="${draft.id}"]`;
  await click(`${card} .person-organization-actions button`);
  await input('[name="person-tags"]', 'منتخب، research, research');
  await click('.group-memberships input');
  await click('.modal-inner button[type=submit]');
  await waitFor(`document.querySelector(${JSON.stringify(card)})?.innerText.includes('research') && !document.querySelector('[name="person-tags"]')`);
  assert.deepEqual((await read()).tags[draft.id], ['منتخب', 'research']);
  assert.deepEqual((await read()).groups[0].personIds, [draft.id]);
  await click(`${card} .person-card-top button`);
  const groupId = (await read()).groups[0].id;
  await evaluate(`(() => { const el = document.querySelector('[aria-label="Filter by group"]'); el.value = ${JSON.stringify(groupId)}; el.dispatchEvent(new Event('change', {bubbles:true})); })()`);
  await waitFor("document.querySelectorAll('.person-card').length === 1");
  await click('.directory-organization button.text-link');
  await input('#directory-group-name', 'My collection');
  await click('.group-form button[type=submit]');
  await waitFor("document.querySelector('[aria-label=\"Filter by group\"]').selectedOptions[0].textContent.includes('My collection')");
  await click(`${card} .person-organization-actions button`);
  await input('[name="person-tags"]', 'updated');
  await click('.modal-inner button[type=submit]');
  await waitFor(`document.querySelector(${JSON.stringify(card)})?.innerText.includes('updated')`);
  await click(`${card} .person-organization-actions button:nth-child(2)`);
  await waitFor("document.querySelector('[name=character-name]').value === 'Bilingual tester'");
  await input('[name="character-title"]', 'Edited office');
  await input('[name="character-title-fa"]', 'سمت ویرایش شده');
  await click('.character-form button[type=submit]');
  await waitFor("[...document.querySelectorAll('.custom-character p')].some(el => el.textContent === 'Edited office')");
  const edited = await read();
  assert.equal(edited.people.length, 1, 'Edit does not create a second draft');
  assert.equal(edited.people.filter(person => person.id === draft.id).length, 1, 'Edit keeps draft identity');
  assert.equal(edited.people[0].titleFa, 'سمت ویرایش شده');
  assert.ok(edited.bookmarks.includes(draft.id));
  assert.deepEqual(edited.tags[draft.id], ['updated']);
  await navigate(fixtureOrigin);
  await waitFor("document.querySelector('.world-map')");
  await click('#test-directory');
  await waitFor(`document.querySelector(${JSON.stringify(card)})?.innerText.includes('My collection')`);
  await click('#test-account');
  await waitFor("document.querySelector('#test-account').textContent === 'fixture-b'");
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Filter by group\"]').options.length"), 1, 'Groups are account scoped');
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Filter by tag\"]').options.length"), 1, 'Tags are account scoped');
  await click('#test-account');
  await waitFor(`document.querySelector(${JSON.stringify(card)})`);
  await click('[data-testid="language-switcher"]');
  await waitFor(`document.querySelector(${JSON.stringify(card + ' h3')})?.textContent === 'شخصیت دوزبانه'`);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(card + ' p')}).textContent`), 'سمت ویرایش شده');
  await cdp("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await evaluate(`(() => { const el = document.querySelector('.directory-organization select'); el.value = ${JSON.stringify(groupId)}; el.dispatchEvent(new Event('change', {bubbles:true})); })()`);
  await waitFor("document.querySelectorAll('.person-card').length === 1");
  assert.equal(await evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), true, 'Persian directory fits mobile width');
  await screenshot('atlas-directory-organization-fa');
  await click('[data-testid="language-switcher"]');
  await click('#test-approve');
  await waitFor(`!JSON.parse(localStorage.getItem('atlas-people-v1:fixture-a')).people.some(person => person.id === ${JSON.stringify(draft.id)})`);
  const sharedId = 'aaaaaaaa-1111-4111-a111-111111111111';
  const approved = await read();
  assert.ok(approved.bookmarks.includes(sharedId)); assert.deepEqual(approved.tags[sharedId], ['updated']);
  assert.deepEqual(approved.groups[0].personIds, [sharedId]);
  await waitFor(`document.querySelectorAll('.person-card[data-person-id="${sharedId}"]').length === 1 && !document.querySelector(${JSON.stringify(card)})`);
  await click('.directory-organization .directory-filters button:nth-of-type(2)');
  await waitFor("JSON.parse(localStorage.getItem('atlas-people-v1:fixture-a')).groups.length === 0");
  assert.equal(await evaluate(`document.querySelectorAll('.person-card[data-person-id="${sharedId}"]').length`), 1, 'Deleting a group keeps its characters');
  await click('#test-directory');
  await waitFor("document.querySelector('.world-map')");
  await click('button[aria-label="Enter fullscreen"]');
  await waitFor("document.querySelector('.map-expanded')");
  await click('button[aria-label="Highlight characters"]');
  await input('[aria-label="Search characters"]', 'Bilingual tester');
  await waitFor("document.querySelectorAll('.highlight-options input').length === 1");
  await click('.highlight-options input');
  await waitFor(`document.querySelector('.map-pin[data-person-id="${sharedId}"].highlighted')`);
  assert.equal(await evaluate("(() => { const r = document.querySelector('#map-highlight-picker').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; })()"), true, 'Highlight picker fits fullscreen mobile');
  await screenshot('atlas-highlight-mobile');
  await click('button[aria-label="Close"]');
  await click('button[aria-label="Exit fullscreen"]');
  await waitFor("!document.querySelector('.map-expanded')");
  assert.equal(await evaluate(`Boolean(document.querySelector('.map-pin[data-person-id="${sharedId}"].highlighted'))`), true, 'Highlights survive leaving fullscreen');
  await click('button[aria-label="Enter fullscreen"]');
  await waitFor("document.querySelector('.map-expanded') && document.querySelector('button[aria-label=\"Highlight characters\"]')");
  await click('button[aria-label="Highlight characters"]');
  await click('#map-highlight-picker > button');
  await waitFor("!document.querySelector('.map-pin.highlighted')");
  await click('button[aria-label="Exit fullscreen"]');
  await waitFor("!document.querySelector('.map-expanded')");
  console.log('PASS: bilingual creation/editing, private tags and groups, rename/filter, persistence/account isolation, approval cleanup and fullscreen highlights.');
}
