import assert from "node:assert/strict";

export async function runMapToolsFeedbackQA({ evaluate, cdp, click, input, waitFor, navigate, screenshot, fixtureOrigin }) {
  await cdp("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1080, deviceScaleFactor: 1, mobile: false });
  await cdp("Emulation.setTouchEmulationEnabled", { enabled: false });
  await navigate(fixtureOrigin);
  await waitFor("document.querySelector('.world-map') && document.querySelector('.map-pin')");
  await cdp('Page.bringToFront');
  await evaluate("localStorage.setItem('atlas-map-tour-v1', 'done')");
  const initialPins = await evaluate("[...document.querySelectorAll('.map-pin')].map(el => el.dataset.personId)");
  await click('#test-directory');
  await waitFor("document.querySelector('.person-card')");
  const selected = await evaluate(`(() => { const card = [...document.querySelectorAll('.person-card')].find(el => !${JSON.stringify(initialPins)}.includes(el.dataset.personId)); return { id: card.dataset.personId, name: card.querySelector('h3').textContent }; })()`);
  const card = `.person-card[data-person-id="${selected.id}"]`;
  await input('#directory-group-name', 'Private speaker group');
  await click('.group-form button[type=submit]');
  await click(`${card} .person-organization-actions button`);
  await input('[name=person-tags]', 'نقشه‌شخصی');
  await click('.group-memberships input');
  await click('.modal-inner button[type=submit]');
  await waitFor("!document.querySelector('[name=person-tags]')");
  for (const query of ['نقشه شخصی', 'Private speaker group']) {
    await input('[aria-label="Search people, tags or groups"]', query);
    await waitFor(`document.querySelectorAll('.person-card').length === 1 && document.querySelector(${JSON.stringify(card)})`);
  }
  await screenshot('atlas-private-group-search');
  await click(`${card} .person-card-bottom button`);
  await waitFor(`document.querySelector('.map-pin.selected-person')?.dataset.personId === ${JSON.stringify(selected.id)}`);
  assert.equal(await evaluate("[...document.querySelectorAll('.world-map .map-pin')].at(-1).dataset.personId"), selected.id, 'Selected clustered member paints last');
  await click('#test-map-controls');
  await waitFor("!document.querySelector('.map-pin.selected-person')");
  await click('button[aria-label="Enter fullscreen"]');
  await waitFor("document.querySelector('.map-expanded')");
  const view = await evaluate("document.querySelector('.world-map > g').getAttribute('transform')");
  await click('button[aria-label="Red laser pointer"]');
  await waitFor("document.querySelector('.map-laser-active')");
  assert.match(await evaluate("getComputedStyle(document.querySelector('.country')).cursor"), /laser\.svg/);
  assert.doesNotMatch(await evaluate("getComputedStyle(document.querySelector('.map-controls button')).cursor"), /laser\.svg/, 'Toolbar keeps ordinary controls');
  assert.equal(await evaluate("document.querySelector('.map-drawing').dataset.drawingTool"), 'pan');
  const stage = await evaluate("(() => { const r = document.querySelector('.map-stage').getBoundingClientRect(); return {x:r.x+r.width*.45,y:r.y+r.height*.65}; })()");
  await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', ...stage });
  assert.equal(await evaluate("document.querySelector('.world-map > g').getAttribute('transform')"), view);
  assert.equal(await evaluate("document.querySelectorAll('[data-pencil-stroke]').length"), 0, 'Laser motion leaves no ink');
  assert.equal(await evaluate("fetch('/cursors/laser.svg').then(r => r.text()).then(text => text.includes('#ff2020'))"), true, 'Red cursor asset is served');
  await click('button[aria-label="Drawing tools"]');
  await waitFor("document.querySelector('[aria-label=\"Pencil width\"]') && !document.querySelector('.map-laser-active')");
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  const inkPoint = await evaluate("(() => { const r = document.querySelector('.map-drawing').getBoundingClientRect(); return {x:r.x+r.width*.5,y:r.y+r.height*.5}; })()");
  const stroke = async offset => {
    assert.equal(await evaluate(`document.elementFromPoint(${inkPoint.x},${inkPoint.y+offset})?.closest('.map-drawing') !== null`), true, 'Stroke hits the drawing surface');
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: inkPoint.x-30, y: inkPoint.y+offset });
    await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', x: inkPoint.x-30, y: inkPoint.y+offset, button: 'left', clickCount: 1 });
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: inkPoint.x+30, y: inkPoint.y+offset, button: 'left', buttons: 1 });
    await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', x: inkPoint.x+30, y: inkPoint.y+offset, button: 'left', clickCount: 1 });
  };
  await input('[aria-label="Pencil width"]', '10');
  await stroke(0);
  await waitFor("document.querySelector('[data-pencil-stroke]')", 'A thick pencil stroke is drawn');
  await input('[aria-label="Pencil width"]', '2');
  await stroke(50);
  await waitFor("document.querySelectorAll('[data-pencil-stroke]').length === 2");
  assert.deepEqual(await evaluate("[...document.querySelectorAll('[data-pencil-stroke]')].map(el => el.getAttribute('stroke-width'))"), ['10', '2'], 'Each stroke keeps its original width');
  await screenshot('atlas-pencil-width');
  await click('button[aria-label="Exit fullscreen"]');
  await waitFor("!document.querySelector('.map-expanded')");
  assert.doesNotMatch(await evaluate("getComputedStyle(document.querySelector('.country')).cursor"), /laser\.svg/);
  for (const [width, height] of [[320, 640], [844, 390]]) {
    await cdp("Emulation.setDeviceMetricsOverride", { width, height, deviceScaleFactor: 1, mobile: true });
    await click('[data-testid=language-switcher]');
    await waitFor("document.documentElement.lang === 'fa'");
    assert.equal(await evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), true, 'Larger Persian text links fit mobile');
    assert.ok(await evaluate("parseFloat(getComputedStyle(document.querySelector('.timeline-heading .text-link')).fontSize) >= 13"));
    await click('button[aria-label="نمایش تمام‌صفحه"]');
    await waitFor("document.querySelector('.map-expanded')");
    assert.ok(await evaluate("(() => { const r = document.querySelector('.map-controls').getBoundingClientRect(); return r.bottom <= innerHeight && r.right <= innerWidth && r.left >= 0; })()"), 'Fullscreen toolbar remains reachable');
    assert.equal(await evaluate("(() => { const button = document.querySelector('.timeline-play'); const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)); })()"), true, 'Toolbar does not cover timeline playback');
    await screenshot(`atlas-map-tools-fa-${width}`);
    await click('button[aria-label="خروج از تمام‌صفحه"]');
    await click('[data-testid=language-switcher]');
  }

  await cdp("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1080, deviceScaleFactor: 1, mobile: false });
  await navigate(`${fixtureOrigin}?fixture=feedback`);
  await waitFor("document.querySelector('[name=feedback-subject]')");
  await input('[name=feedback-subject]', '<b>Map bug</b>');
  await input('textarea[name=feedback-body]', 'First line\nSecond line <img src=x onerror=alert(1)>');
  await click('#test-feedback-failure');
  await click('.feedback-page button[type=submit]');
  await waitFor("document.querySelector('.feedback-page .form-error')");
  assert.equal(await evaluate("document.querySelector('[name=feedback-subject]').value"), '<b>Map bug</b>', 'Failed sends keep the draft');
  await click('#test-feedback-failure');
  await click('.feedback-page button[type=submit]');
  await waitFor("document.querySelector('.feedback-page .form-success')");
  assert.equal(await evaluate("document.querySelector('[name=feedback-subject]').value"), '');
  await click('#test-feedback-admin');
  await waitFor("document.querySelector('#admin-tab-feedback')");
  await click('#admin-tab-feedback');
  await waitFor("document.querySelector('.feedback-message')");
  assert.equal(await evaluate("document.querySelectorAll('.feedback-message').length"), 1, 'One message reaches the administrator inbox');
  assert.equal(await evaluate("document.querySelector('.feedback-message h3').textContent"), '<b>Map bug</b>');
  assert.equal(await evaluate("document.querySelectorAll('.feedback-message img,.feedback-message b').length"), 0, 'Message text cannot inject markup');
  await click('.feedback-message .secondary-button');
  await waitFor("document.querySelector('.feedback-read')");
  await click('.feedback-message .primary-button');
  await waitFor("document.querySelector('.feedback-resolved')");
  await click('.feedback-inbox .admin-toolbar button');
  await waitFor("document.querySelector('.feedback-resolved')");
  await input('[aria-label="Search messages"]', 'qa@example.test');
  await waitFor("document.querySelectorAll('.feedback-message').length === 1");
  await cdp("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await click('[data-testid=language-switcher]');
  await waitFor("document.documentElement.lang === 'fa'");
  assert.equal(await evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), true, 'Persian feedback inbox fits mobile');
  await screenshot('atlas-feedback-inbox-fa');
  await click('#test-feedback-user');
  await screenshot('atlas-feedback-form-fa');
  await navigate(`${fixtureOrigin}?fixture=feedback&mode=local`);
  await waitFor("document.querySelector('.feedback-page button[type=submit]:disabled')");
  assert.match(await evaluate("document.querySelector('.feedback-page').textContent"), /online account/);
  await navigate(fixtureOrigin);
  await waitFor("document.querySelector('.world-map')");
  console.log('PASS: red laser cursor, per-stroke widths, selected portrait stacking, private tag/group search, larger RTL/mobile text and user-to-admin feedback flow.');
}
