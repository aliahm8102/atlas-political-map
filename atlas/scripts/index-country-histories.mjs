import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const historyDirectory = fileURLToPath(new URL("../data/country-history/", import.meta.url));
export async function countryHistoryIndex(directory = historyDirectory) {
  const files = (await fs.readdir(directory)).filter(file => file.endsWith(".json") && !["template.json", "schema.json"].includes(file)).sort();
  const imports = [], entries = [];
  for (const [index, file] of files.entries()) {
    const data = JSON.parse(await fs.readFile(path.join(directory, file), "utf8"));
    if (file !== `${data.code}.json` || !/^[a-z0-9-]+$/.test(data.code)) throw new Error(`Country code does not match history filename: ${file}`);
    imports.push(`import country${index} from "./${file}" with { type: "json" };`);
    entries.push(`  "${data.code}": country${index},`);
  }
  return `// Generated by npm run data:index-countries. Edit individual country JSON files.\n${imports.join("\n")}\n\nconst histories = {\n${entries.join("\n")}\n};\nexport default histories;\n`;
}
export async function writeCountryHistoryIndex(directory = historyDirectory) {
  await fs.writeFile(path.join(directory, "index.ts"), await countryHistoryIndex(directory));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeCountryHistoryIndex();
  console.log("Updated the country history index.");
}
